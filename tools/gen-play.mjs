// Writes tests/native/journey-match.play: journey stage 1 (First Table,
// seeded) played to its results through the real UI. The match is first
// simulated in Node with the shipped js/session.js — its AI turns on timers
// that this tool runs in order, exactly as the engine client runs them on
// its fixed steps (60 a second) — with the human taking the first legal
// action each turn; each human move becomes clicks on the hand tile and the
// end cap (draw and pass: W and S), each wait for the AI the frames its
// thinking delays take. Run after changing the rules, the AI or the content.
//   node tools/gen-play.mjs
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const R = require('../js/rules.js');
const C = require('../js/content.js');
const { Session } = require('../js/session.js');

const STEP_MS = 1000 / 60;
const queue = [];
let seq = 0;
const timers = {
  setTimeout(fn, ms) { const id = ++seq; queue.push({ id, ms, fn }); return id; },
  clearTimeout(id) { const i = queue.findIndex((t) => t.id === id); if (i >= 0) queue.splice(i, 1); },
};
const store = {
  doc: { profile: { name: 'Guest' } }, profile: { name: 'Guest' },
  progress: { journey: {}, tutorials: [], achievements: {}, stats: { matches: 0, wins: 0, streak: 0, bestStreak: 0, rounds: 0, dominos: 0 }, daily: {}, masteryXP: 0 },
  settings: { timingAssist: false, reducedMotion: false },
  saveNow() {}, now() { return 0; },
};
const s = new Session({ store, audio: null, timers, externalClock: true });
const stage = C.JOURNEY[0];
s.startMatch('journey', stage, C.stageToConfig(stage, 'Guest'), { undo: true, hints: true, ranked: false, timeLimitSec: 0 });

const out = [
  '# Generated by tools/gen-play.mjs: journey stage 1 (First Table) played to its',
  '# results — each human turn the first legal action (a hand tile, then its end',
  '# cap; draw W, pass S), each AI turn waited for by its thinking frames.',
  'until 300 Chain Dominoes',
  'frames 20',
  'click Journey',
  'until 60 Forty tables',
  'frames 10',
  'click First Table',
  'until 200 YOUR HAND',
  'frames 30',
];
/** Runs the AI's pending turns; the frames they took. */
function runTimers() {
  let ms = 0;
  while (queue.length) { const t = queue.shift(); ms += t.ms; t.fn(); }
  return Math.ceil(ms / STEP_MS);
}
let waitFrames = runTimers();
let moves = 0, rounds = 1;
const me = 0;
for (let guard = 0; guard < 2000; guard++) {
  const st = s.state;
  if (st.phase === 'match-over') break;
  if (st.phase === 'round-over') {
    out.push(`frames ${waitFrames + 20}`, 'until 300 Next round', 'frames 10');
    if (rounds === 1) out.push('save round-over');
    out.push('click Next round', 'frames 40');
    s.continueNextRound();
    rounds++;
    waitFrames = runTimers();
    continue;
  }
  if (st.turn !== me) { waitFrames += runTimers(); continue; }
  if (waitFrames) { out.push(`frames ${waitFrames + 20}`); waitFrames = 0; }
  out.push('until 300 Your turn', 'frames 10');
  const acts = R.legalActions(st, me);
  const a = acts.find((x) => x.type === 'play') || acts[0];
  if (a.type === 'play') {
    const t = R.tileOf(st, a.tileId);
    out.push(`click ${t.a} | ${t.b} domino`, 'frames 8', `click Play selected tile on ${a.end} end`, 'frames 30');
  } else out.push(`key ${a.type === 'draw' ? 'KeyW' : 'KeyS'} 2`, 'frames 30');
  if (moves === 2) out.push('save mid-match');
  moves++;
  const res = s.act(a, 'g' + moves);
  if (!res.ok) throw new Error('rejected ' + JSON.stringify(a) + ' ' + res.reason);
  waitFrames = runTimers();
}
if (s.state.phase !== 'match-over') throw new Error('the match did not finish');
const t = s.state.terminal;
out.push(`frames ${waitFrames + 20}`, 'until 600 Play again', 'frames 30', 'save results',
  `expect ${t.winner === me ? 'You win the table!' : 'takes the table'}`);
writeFileSync(join(root, 'tests/native/journey-match.play'), out.join('\n') + '\n');
console.log(`journey-match.play: ${moves} human moves, ${rounds} rounds, winner ${t.winner}, scores ${t.scores.join('/')}`);
